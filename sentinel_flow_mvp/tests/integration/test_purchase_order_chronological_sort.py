def test_purchase_orders_sort_chronologically(override_get_db):
    """
    Test proves that multiple orders on the same day are sorted chronologically by created_at.
    """
    client = TestClient(app)
    
    res = client.get("/api/v1/purchase-orders", headers={"x-tenant-id": "T1"})
    assert res.status_code == 200
    data = res.json()
    
    assert len(data) == 3
    order_sequence = [po["po_id"] for po in data]
    
    # We expect newest first due to .desc()
    expected_sequence = ["PO-NEWEST", "PO-MIDDLE", "PO-OLDEST"]
    assert order_sequence == expected_sequence, f"Expected {expected_sequence}, got {order_sequence}"

def test_purchase_order_endpoint_auto_populates_created_at(override_get_db):
    """
    Proves that creating a PO via the endpoint automatically populates created_at
    due to the server_default=func.now(), without needing code changes to the router.
    """
    client = TestClient(app)
    
    payload = {
        "supplier_id": "SUPP-1",
        "expected_delivery_date": str(date(2026, 8, 4)),
        "items": [
            {
                "sku_id": "SKU-AUTO",
                "ordered_qty": 5,
                "cost_price": 10.0,
                "expected_mrp": 15.0
            }
        ]
    }
    
    # Create via endpoint
    res = client.post("/api/v1/purchase-orders", headers={"x-tenant-id": "T1"}, json=payload)
    assert res.status_code == 200
    
    # The real proof is querying the DB directly to see if created_at was generated
    from app.infrastructure.database import SessionLocal
    db_res = client.app.dependency_overrides[get_database_session]()
    db = next(db_res)
    
    db_po = db.query(PurchaseOrderModel).filter(PurchaseOrderModel.sku_id == "SKU-AUTO").first()
    assert db_po is not None
    assert db_po.created_at is not None, "Database did not automatically populate created_at!"
    print(f"Automatically populated created_at by endpoint: {db_po.created_at}")
